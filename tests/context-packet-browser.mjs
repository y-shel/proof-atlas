import puppeteer from 'puppeteer-core';
import assert from 'node:assert/strict';
import { readFile, writeFile, mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { loadGraph } from '../web/graph-model.js';
import { buildContextPacket, serializeContextPacket } from '../web/context-packet.js';
const browser = await puppeteer.launch({ executablePath: '/sbin/chromium', headless: true });
try {
  const page = await browser.newPage();
  await page.setViewport({width: 1500, height: 1000});
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(process.env.PROOF_ATLAS_URL ?? 'http://127.0.0.1:5173');
  await page.click('#demo'); await page.waitForSelector('.chunk');
  await page.select('#declaration', 'repeated');
  const raw = JSON.parse(await readFile('web/public/demo.json', 'utf8'));
  const model = await loadGraph(raw);
  const chunk = raw.chunks.find(c => c.declarationId === 'repeated' && c.text === 'exact hp');
  await page.click(`.chunk[data-id="${chunk.id}"]`);
  const camera = await page.$eval('#graph', n => n.dataset.camera);
  const expected = serializeContextPacket(buildContextPacket(model, chunk.id));
  assert.equal(await page.$eval('#packet-preview', n => n.textContent), expected);
  assert.match(await page.$eval('#packet-status', n => n.textContent), /ready/);
  await page.evaluate(() => {
    const original = URL.createObjectURL;
    URL.createObjectURL = function(blob) { window.downloadedPacket = blob; return original.call(this, blob); };
  });
  await page.click('#packet-download');
  assert.equal(await page.evaluate(() => window.downloadedPacket.text()), expected);
  await page.$eval('#packet-budget', n => n.scrollIntoView({block: 'center'}));
  await page.screenshot({path: '/tmp/proof-atlas-context-packet.png'});
  await page.$eval('#packet-budget', n => { n.value = '2000'; });
  await page.click('#packet-build');
  assert.match(await page.$eval('#packet-status', n => n.textContent), /over_limit/);
  const tight = JSON.parse(await page.$eval('#packet-preview', n => n.textContent));
  assert.equal(tight.evidence, undefined);
  assert.ok(Buffer.byteLength(JSON.stringify(tight)+'\n') <= 2000);
  assert.equal(await page.$eval('#graph', n => n.dataset.camera), camera);
  await page.$eval('#packet-budget', n => { n.value = '1'; });
  await page.click('#packet-build');
  assert.match(await page.$eval('#packet-status', n => n.textContent), /too small/);
  assert.equal(await page.$eval('#packet-download', n => n.disabled), true);
  const missingSource = structuredClone(raw);
  const changed = missingSource.chunks.find(c => c.id === chunk.id);
  changed.source = { classification: 'synthetic', startByte: null, endByte: null };
  changed.text = null;
  for (const id of changed.occurrenceIds) missingSource.evidence.records[id].source = changed.source;
  const temporary = await mkdtemp(join(tmpdir(), 'packet-browser-'));
  const file = join(temporary, 'missing-source.json');
  await writeFile(file, JSON.stringify(missingSource));
  await (await page.$('#file')).uploadFile(file);
  await page.waitForFunction(() => document.querySelector('#status').textContent.startsWith('missing-source.json'));
  await page.select('#declaration', 'repeated');
  await page.click(`.chunk[data-id="${chunk.id}"]`);
  await page.$eval('#packet-budget', n => { n.value = '131072'; });
  await page.click('#packet-build');
  assert.match(await page.$eval('#packet-status', n => n.textContent), /unavailable/);
  const unavailable = JSON.parse(await page.$eval('#packet-preview', n => n.textContent));
  assert.equal(unavailable.evidence, undefined);
  assert.ok(unavailable.retrieval.length);
  assert.deepEqual(errors, []);
  console.log('Packet browser checks passed: exact download parity, repeated selection, budget status, stable camera.');
} finally { await browser.close(); }
