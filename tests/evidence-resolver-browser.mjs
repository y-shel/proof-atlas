import puppeteer from 'puppeteer-core';
import assert from 'node:assert/strict';
import { readFile, writeFile, mkdtemp } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { loadGraph } from '../web/graph-model.js';
import { buildContextPacket } from '../web/context-packet.js';
import { resolveEvidence, serializeEvidenceResult, evidenceResultBytes } from '../web/evidence-resolver.js';

const temporary = await mkdtemp(join(tmpdir(), 'evidence-browser-'));
let mediumGraph = process.env.EVIDENCE_MEDIUM_GRAPH;
if (!mediumGraph) {
  const source = 'experiments/native-extraction/AxiomAudit.lean', evidence = join(temporary, 'medium-evidence.json');
  mediumGraph = join(temporary, 'medium.json');
  execFileSync('python3', ['scripts/export_evidence.py', source, '--declaration', 'AuditFixture.tallyAppend', '--declaration', 'AuditFixture.unicodeBasis', '--output', evidence]);
  execFileSync('python3', ['scripts/project_graph.py', evidence, '--source', source, '--output', mediumGraph]);
}
const browser = await puppeteer.launch({ executablePath: '/sbin/chromium', headless: true });
try {
  const page = await browser.newPage();
  await page.setViewport({ width: 1500, height: 1000 });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(process.env.PROOF_ATLAS_URL ?? 'http://127.0.0.1:5173');
  await page.click('#demo'); await page.waitForSelector('.chunk');
  const raw = JSON.parse(await readFile('web/public/demo.json', 'utf8'));
  const m = await loadGraph(raw);
  await page.select('#declaration', 'repeated');
  const c = raw.chunks.find(c => c.declarationId === 'repeated' && c.text === 'exact hp');
  await page.click(`.chunk[data-id="${c.id}"]`);
  await page.waitForFunction(() => document.querySelector('#graph').dataset.camera);
  const graphState = () => page.$eval('#graph', n => ({camera: n.dataset.camera, layout: n.dataset.layout}));
  const before = await graphState();
  const selected = () => page.$eval('.chunk[aria-pressed="true"]', n => n.dataset.id);
  const p = buildContextPacket(m, c.id), anchors = [...p.citations, ...p.retrieval];
  assert.equal(await page.$$eval('#evidence-anchor option', ns => ns.length), anchors.length);
  const exactIndex = anchors.findIndex(a => a.packetPath?.at(-1) === 'directValueAdmission');
  assert.ok(exactIndex >= 0);
  await page.select('#evidence-anchor', String(exactIndex));
  await page.click('#evidence-inspect');
  const resultText = () => page.$eval('#evidence-result', n => n.textContent);
  assert.equal(await resultText(), serializeEvidenceResult(resolveEvidence(m, anchors[exactIndex])));
  assert.equal(JSON.parse(await resultText()).value, false);
  assert.deepEqual(await graphState(), before);
  assert.equal(await selected(), c.id);

  await page.select('#evidence-anchor', '0');
  assert.equal(await resultText(), '');
  await page.click('#evidence-inspect');
  const ready = JSON.parse(await resultText()), bytes = evidenceResultBytes(ready);
  assert.deepEqual(ready.value, c);
  await page.$eval('#evidence-budget', (n, value) => { n.value = value; n.dispatchEvent(new Event('input')); }, String(bytes));
  assert.equal(await resultText(), '');
  await page.click('#evidence-inspect');
  assert.equal(JSON.parse(await resultText()).status, 'ready');
  await page.$eval('#evidence-budget', (n, value) => { n.value = value; }, String(bytes - 1));
  await page.click('#evidence-inspect');
  const tight = JSON.parse(await resultText());
  assert.equal(tight.status, 'over_limit'); assert.equal(tight.requiredBytes, bytes);
  assert.equal(Object.hasOwn(tight, 'value'), false);
  assert.deepEqual(await graphState(), before); assert.equal(await selected(), c.id);
  await page.$eval('#evidence-budget', n => { n.value = '1'; });
  await page.click('#evidence-inspect');
  assert.match(await page.$eval('#evidence-status', n => n.textContent), /too small/);
  assert.equal(await resultText(), '');

  await page.$eval('#packet-budget', n => { n.value = '2000'; });
  await page.click('#packet-build');
  assert.match(await page.$eval('#packet-status', n => n.textContent), /over_limit/);
  assert.equal(await resultText(), '');
  assert.ok(await page.$$eval('#evidence-anchor option', ns => ns.length));
  await page.$eval('#evidence-budget', n => { n.value = '131072'; });
  await page.click('#evidence-inspect');
  assert.equal(JSON.parse(await resultText()).status, 'ready');
  assert.deepEqual(await graphState(), before);
  await page.select('#declaration', 'branches'); assert.equal(await resultText(), '');

  const mismatch = structuredClone(raw); mismatch.evidence.artifactId = 'sha256:' + '0'.repeat(64);
  const mismatchFile = join(temporary, 'mismatch.json'); await writeFile(mismatchFile, JSON.stringify(mismatch));
  await (await page.$('#file')).uploadFile(mismatchFile);
  await page.waitForFunction(() => document.querySelector('#status').textContent.startsWith('mismatch.json'));
  await page.click('#evidence-inspect');
  const unavailable = JSON.parse(await resultText());
  assert.equal(unavailable.status, 'unavailable'); assert.equal(Object.hasOwn(unavailable, 'value'), false);
  assert.match(unavailable.reason, /identity/);

  await (await page.$('#file')).uploadFile(mediumGraph);
  await page.waitForFunction(name => document.querySelector('#status').textContent.startsWith(name), {}, mediumGraph.split('/').at(-1));
  assert.equal(await resultText(), '');
  await page.select('#declaration', 'AuditFixture.tallyAppend');
  const medium = await loadGraph(JSON.parse(await readFile(mediumGraph, 'utf8')));
  const mc = medium.chunks('AuditFixture.tallyAppend').find(c => c.text.startsWith('have shared'));
  await page.click(`.chunk[data-id="${mc.id}"]`);
  assert.match(await page.$eval('#packet-status', n => n.textContent), /over_limit/);
  await page.click('#evidence-inspect');
  const mr = JSON.parse(await resultText()); assert.equal(mr.status, 'ready');
  assert.deepEqual(mr.value, mc);
  await page.$eval('#packet-budget', n => { n.value = '262144'; }); await page.click('#packet-build');
  assert.match(await page.$eval('#packet-status', n => n.textContent), /ready/);
  const mp = buildContextPacket(medium, mc.id, {maxBytes: 262144});
  const ma = [...mp.citations, ...mp.retrieval];
  const di = ma.findIndex(a => a.path[1] === 'declarations'); assert.ok(di >= 0);
  await page.select('#evidence-anchor', String(di));
  const mediumBefore = await graphState();
  await page.click('#evidence-inspect');
  assert.equal(await resultText(), serializeEvidenceResult(resolveEvidence(medium, ma[di])));
  assert.deepEqual(await graphState(), mediumBefore); assert.equal(await selected(), mc.id);
  await page.select('#declaration', 'AuditFixture.unicodeBasis');
  assert.equal(await resultText(), '');
  await page.click('.chunk'); await page.click('#evidence-inspect');
  const unicode = JSON.parse(await resultText()); assert.equal(unicode.status, 'ready');
  assert.ok(unicode.value.text.includes('𝕫'));
  await page.$eval('#evidence-result', n => n.scrollIntoView({block: 'center'}));
  await page.screenshot({path: '/tmp/proof-atlas-evidence-retrieval.png'});
  assert.deepEqual(errors, []);
  console.log('Evidence browser checks passed: exact scalar/Unicode values, bounds, unavailable identity, stale clearing, small/medium anchors and unchanged selection/camera/layout.');
} finally { await browser.close(); }
